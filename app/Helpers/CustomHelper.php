    /**
     * Get validation rules for custom fields by module.
     *
     * @param string $module
     * @return array
     */
    public static function getCustomFieldRules(string $module,int $id = 0): array
    {
        $rules = [];
        $attributes = [];

        $customFields = CustomField::where('module', 'cms')->where(function ($query) use ($id) {
            $query->where('ref_id', 0)
            ->orWhere('ref_id', $id);
        })->get();

        foreach ($customFields as $field) {
            $rulesList = [];

            $validationJson = json_decode($field->validation ?? '{}', true);
            $fileConstraints = json_decode($field->file_constraints ?? '{}', true);

            // Required or Nullable
            $rulesList[] = !empty($validationJson['required']) ? 'required' : 'nullable';

            // Field type based rules
            $rulesList[] = match ($field->field_type) {
                'number' => 'numeric',
                'email' => 'email',
                'date' => 'date',
                'file', 'image' => $field->field_type,
                default => '',
            };

            // Other validation rules
            foreach ($validationJson as $key => $value) {
                if ($key === 'required') continue;

                switch ($key) {
                    case 'max':
                    case 'min':
                    case 'size':
                    case 'digits':
                        $rulesList[] = "$key:$value";
                        break;

                    case 'between':
                    case 'digits_between':
                        $rulesList[] = "$key:" . implode(',', (array) $value);
                        break;

                    case 'regex':
                        // Ensure regex is wrapped properly
                        if (is_string($value) && preg_match('/^\/.*\/[a-z]*$/i', $value)) {
                            $rulesList[] = "regex:$value";
                        }
                        break;

                    case 'in':
                        $rulesList[] = 'in:' . implode(',', (array) $value);
                        break;

                    default:
                        if (!is_bool($value)) {
                            $rulesList[] = "$key:$value";
                        }
                }
            }

            // File constraints
            if (in_array($field->field_type, ['file', 'image'])) {
                if (!empty($fileConstraints['max_size'])) {
                    $rulesList[] = "max:" . $fileConstraints['max_size'];
                }

                if (!empty($fileConstraints['types'])) {
                    $rulesList[] = "mimes:" . implode(',', (array) $fileConstraints['types']);
                }

                if (!empty($fileConstraints['width']) || !empty($fileConstraints['height'])) {
                    $dimensions = [];

                    if (!empty($fileConstraints['width'])) {
                        $dimensions[] = "width={$fileConstraints['width']}";
                    }

                    if (!empty($fileConstraints['height'])) {
                        $dimensions[] = "height={$fileConstraints['height']}";
                    }

                    $rulesList[] = 'dimensions:' . implode(',', $dimensions);
                }
            }

            $key = "custom_fields.{$field->key}";
            $rules[$key] = $rulesList;
            $attributes[$key] = $field->label;
        }

        return [
            'rules' => $rules,
            'attributes' => $attributes,
        ];
    }

    /**
     * Generate a unique slug for pages (or any other model).
     *
     * @param string|null $inputSlug
     * @param string $title
     * @param int|null $ignoreId
     * @return string
     */
    public static function generateSlug($slug, $title, $modelClass, $column = 'slug', $ignoreId = null)
    {
        $slug = Str::slug($slug ?: $title);
        $originalSlug = $slug;
        $i = 1;

        while ($modelClass::where($column, $slug)
            ->when($ignoreId, fn($q) => $q->where('id', '!=', $ignoreId))
            ->exists()) {
            $slug = $originalSlug . '-' . $i;
            $i++;
        }
        return $slug;
    }

