    public static function UploadImage($file, $path, $ext = "", $width = 768, $height = 768, $is_thumb = false, $thumb_path = "", $thumb_width = 300, $thumb_height = 300, $is_medium = false, $medium_path = "", $medium_width = 300, $medium_height = 300) {

        /*ini_set('display_errors', 1);
        ini_set('display_startup_errors', 1);
        error_reporting(E_ALL);*/
        ini_set('memory_limit', -1);

        if (empty($ext)) {
            $ext = "jpg,jpeg,png,gif,webp";
        }
        if (!File::exists(public_path("storage/" . $path))) {
            File::makeDirectory(public_path("storage/" . $path), $mode = 0777, true, true);
        }
        if ($is_thumb && !empty($thumb_path) && !File::exists(public_path("storage/" . $thumb_path))) {
            File::makeDirectory(public_path("storage/" . $thumb_path), $mode = 0777, true, true);
        }
        if ($is_medium && !empty($medium_path) && !File::exists(public_path("storage/" . $medium_path))) {
            File::makeDirectory(public_path("storage/" . $medium_path), $mode = 0777, true, true);
        }
        $filePath = method_exists($file, 'getPathname') ? $file->getPathname() : $file;
        $imgData = @getimagesize($filePath);
        $img_width = isset($imgData[0]) ? $imgData[0] : $width;
        $img_height = isset($imgData[1]) ? $imgData[1] : $height;
        if ($img_width < $width) { $width = $img_width; }
        if ($img_height < $height) { $height = $img_height; }
        $result["success"] = false;
        $result["org_name"] = "";
        $result["file_name"] = "";
        if ($file) {
            $allowedExt = !empty($ext) ? explode(',', $ext) : ["jpg","jpeg","png","gif"];
            $extension = method_exists($file, 'getClientOriginalExtension') ? $file->getClientOriginalExtension() : pathinfo($filePath, PATHINFO_EXTENSION);
            $extension = strtolower($extension);
            $isUploadedFile = is_object($file) && method_exists($file, 'getClientOriginalExtension');
            $isValidExt = in_array($extension, $allowedExt);
            if ($isUploadedFile) {
                $validator = Validator::make(["file" => $file], ["file" => "mimes:" . implode(',', $allowedExt)]);
                if (!$validator->passes()) {
                    $result["errors"] = $validator->errors();
                    return $result;
                }
            } else {
                if (!$isValidExt) {
                    $result["errors"]["file"] = "Invalid image type";
                    return $result;
                }
            }
            $handle = @fopen($filePath, "rb");
            $opening_bytes = '';
            if ($handle) {
                $opening_bytes = fread($handle, min(filesize($filePath), 2048));
                fclose($handle);
            }
            if ($opening_bytes && (strlen(strpos($opening_bytes, "<?php")) > 0) && (strpos($opening_bytes, "<?php") >= 0 || strpos($opening_bytes, "<?PHP") >= 0)) {
                $result["errors"]["file"] = "Invalid image!";
            } else {
                $fileOriginalName = method_exists($file, 'getClientOriginalName') ? $file->getClientOriginalName() : basename($filePath);
                $fileOriginalName = pathinfo($fileOriginalName, PATHINFO_FILENAME);
                $fileOriginalName = self::sanitizeUploadFile($fileOriginalName).'.'.$extension;
                $fileName = date("dmyhis") . "-" . $fileOriginalName;
                $is_uploaded = Image::read($filePath)->resize($width, $height, function ($constraint) {
                    $constraint->aspectRatio();
                })->save(public_path("storage/" . $path . $fileName), 85);
                if ($is_uploaded) {
                    $result["success"] = true;
                    if ($is_thumb && !empty($thumb_path)) {
                        Image::read($filePath)->resize($thumb_width, $thumb_height, function ($constraint) {
                            $constraint->aspectRatio();
                        })->save(public_path("storage/" . $thumb_path . $fileName), 75);
                    }
                    if ($is_medium && !empty($medium_path)) {
                        Image::read($filePath)->resize($medium_width, $medium_height, function ($constraint) {
                            $constraint->aspectRatio();
                        })->save(public_path("storage/" . $medium_path . $fileName), 80);
                    }
                    $result["org_name"] = $fileOriginalName;
                    $result["file_name"] = $fileName;
                }
            }
        }
        return $result;
    }

    public static function getImageUrl($fileName, $path, $size = 'large') {
        if (empty($fileName)) return asset('assets/img/placeholder.webp');
        $baseName = basename($fileName);
        $dir = rtrim($path, '/') . '/';
        $storagePath = 'storage/' . $dir;
        if ($size == 'thumb') {
            $storagePath .= 'thumb/';
        } elseif ($size == 'medium') {
            $storagePath .= 'medium/';
        }
        if (\Illuminate\Support\Str::startsWith($fileName, 'uploads/')) {
            $uploadsDir = trim(dirname($fileName), '/') . '/';
            $uploadsPath = 'storage/' . $uploadsDir;
            if ($size == 'thumb') {
                $uploadsPath .= 'thumb/';
            } elseif ($size == 'medium') {
                $uploadsPath .= 'medium/';
            }
            if (file_exists(public_path($uploadsPath . $baseName))) {
                return asset($uploadsPath . $baseName);
            }
        }
        if (file_exists(public_path($storagePath . $baseName))) {
            return asset($storagePath . $baseName);
        }
        if ($size != 'large' && file_exists(public_path('storage/' . $dir . $baseName))) {
            return asset('storage/' . $dir . $baseName);
        }
        if (\Illuminate\Support\Str::startsWith($fileName, 'uploads/') && file_exists(public_path('storage/' . $fileName))) {
            return asset('storage/' . $fileName);
        }
        return asset('assets/img/placeholder.webp');
    }

