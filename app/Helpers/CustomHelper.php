    /**
     * reCAPTCHA v3 Server-Side Verification Helper
     * 
     * This method verifies reCAPTCHA v3 tokens received from the frontend.
     * reCAPTCHA v3 provides a score (0.0-1.0) indicating how likely the user is human.
     * 
     * @param string $token The reCAPTCHA token from frontend (g-recaptcha-response)
     * @return array Google's verification response containing:
     *               - success: boolean (true if verification passed)
     *               - score: float (0.0 = bot, 1.0 = human)
     *               - action: string (action name from frontend)
     *               - challenge_ts: timestamp of challenge
     *               - hostname: domain where challenge was solved
     *               - error-codes: array (if verification failed)
     */
    public static function checkGoogleReCaptcha($token){
        // Retrieve reCAPTCHA secret key from application settings
        // This key should be stored securely in .env file and never exposed to frontend
        $websiteSettingsArr = self::getSettings('RECAPTCHA_SECRET_KEY');

        // Initialize cURL session for HTTP request to Google's verification endpoint
        $ch = curl_init();
        
        // Configure cURL options for reCAPTCHA verification
        curl_setopt($ch, CURLOPT_URL, "https://www.google.com/recaptcha/api/siteverify"); // Google's verification endpoint
        curl_setopt($ch, CURLOPT_POST, 1); // Use POST method (required by Google)
        
        // Prepare POST data with secret key and user's token
        // secret: Your private key from Google reCAPTCHA console
        // response: The token generated by grecaptcha.execute() on frontend
        curl_setopt($ch, CURLOPT_POSTFIELDS, http_build_query(array(
            'secret' => $websiteSettingsArr['RECAPTCHA_SECRET_KEY'],
            'response' => $token
        )));
        
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true); // Return response as string instead of outputting
        
        // Execute the request and get Google's response
        $response = curl_exec($ch);
        curl_close($ch); // Clean up cURL session
       
        // Parse Google's JSON response into PHP array
        // Response format: {"success": true/false, "score": 0.0-1.0, "action": "action_name", ...}
        $arrResponse = json_decode($response, true);
        
        // Debug: Uncomment to inspect Google's full response during development
        // prd($arrResponse);

        // Return the complete response array for further processing
        // Calling code should check $response['success'] and optionally $response['score']
        // Typical score threshold: 0.5 (adjust based on your security requirements)
        return $arrResponse;
    }

